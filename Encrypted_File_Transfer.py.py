def download_file(file_id):

    response = requests.get(
        f"{SERVER_URL}/files/{file_id}/manifest"
    )

    response.raise_for_status()

    manifest = response.json()

    output_path = Path(
        "/content/downloaded_" + Path(manifest["filename"]).name
    )

    print("\nStarting secure download...")

    with open(output_path, "wb") as output:

        for index in range(manifest["chunk_count"]):

            response = requests.get(
                f"{SERVER_URL}/files/{file_id}/{index}"
            )

            response.raise_for_status()

            data = response.json()

            nonce = base64.b64decode(data["nonce"])

            encrypted_data = base64.b64decode(
                data["ciphertext"]
            )

            received_tag = data["hmac"]

            # Verify HMAC before decryption
            valid = verify_hmac(
                file_id,
                index,
                nonce,
                encrypted_data,
                received_tag
            )

            if not valid:
                raise ValueError(
                    f"HMAC verification failed for chunk {index}"
                )

            associated_data = f"{file_id}:{index}".encode()

            # AES-256-GCM decryption
            plain_data = aes.decrypt(
                nonce,
                encrypted_data,
                associated_data
            )

            output.write(plain_data)

            print(f"Verified and decrypted chunk {index + 1}")

    if output_path.stat().st_size != manifest["size"]:
        output_path.unlink(missing_ok=True)
        raise ValueError("File size verification failed")

    print("\nFile downloaded successfully!")
    print("Saved at:", output_path)

    return output_path


