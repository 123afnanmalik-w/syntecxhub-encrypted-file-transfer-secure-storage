def upload_file(file_path):

    file_path = Path(file_path)

    if not file_path.exists():
        raise FileNotFoundError("File does not exist")

    file_size = file_path.stat().st_size

    chunk_count = max(
        1,
        (file_size + CHUNK_SIZE - 1) // CHUNK_SIZE
    )

    response = requests.post(
        SERVER_URL + "/upload/start",
        json={
            "filename": file_path.name,
            "size": file_size,
            "chunk_count": chunk_count
        }
    )

    response.raise_for_status()

    file_id = response.json()["file_id"]

    print("\nStarting encrypted upload...")

    with open(file_path, "rb") as file:

        for index in range(chunk_count):

            plain_data = file.read(CHUNK_SIZE)

            # Generate a unique nonce for every chunk
            nonce = os.urandom(12)

            associated_data = f"{file_id}:{index}".encode()

            # AES-256-GCM encryption
            encrypted_data = aes.encrypt(
                nonce,
                plain_data,
                associated_data
            )

            # HMAC integrity tag
            tag = create_hmac(
                file_id,
                index,
                nonce,
                encrypted_data
            )

            payload = {
                "nonce": base64.b64encode(nonce).decode(),
                "ciphertext": base64.b64encode(encrypted_data).decode(),
                "hmac": tag
            }

            response = requests.post(
                f"{SERVER_URL}/upload/{file_id}/{index}",
                json=payload
            )

            response.raise_for_status()

            print(f"Encrypted chunk {index + 1}/{chunk_count} uploaded")

    response = requests.post(
        f"{SERVER_URL}/upload/{file_id}/finish"
    )

    response.raise_for_status()

    print("\nFile uploaded successfully!")
    print("File ID:", file_id)

    return file_id


