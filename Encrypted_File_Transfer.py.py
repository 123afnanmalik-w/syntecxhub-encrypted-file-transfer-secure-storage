# 4. HMAC INTEGRITY FUNCTION
# ------------------------------------------------------------

def create_hmac(file_id, index, nonce, ciphertext):

    message = (
        f"{file_id}:{index}".encode()
        + nonce
        + ciphertext
    )

    return hmac.new(
        HMAC_KEY,
        message,
        hashlib.sha256
    ).hexdigest()


def verify_hmac(file_id, index, nonce, ciphertext, received_tag):

    expected_tag = create_hmac(
        file_id,
        index,
        nonce,
        ciphertext
    )

    return hmac.compare_digest(expected_tag, received_tag)


