app = Flask(__name__)

@app.route("/", methods=["GET"])
def home():
    return jsonify({"message": "Secure File Transfer Server Running"})

@app.route("/upload/start", methods=["POST"])
def start_upload():

    data = request.get_json()

    file_id = str(uuid.uuid4())

    folder = STORAGE / file_id
    folder.mkdir(parents=True, exist_ok=True)

    manifest = {
        "file_id": file_id,
        "filename": data["filename"],
        "size": data["size"],
        "chunk_count": data["chunk_count"],
        "complete": False
    }

    with open(folder / "manifest.json", "w") as f:
        json.dump(manifest, f)

    return jsonify({"file_id": file_id})


@app.route("/upload/<file_id>/<int:index>", methods=["POST"])
def upload_chunk(file_id, index):

    folder = STORAGE / file_id
    manifest_path = folder / "manifest.json"

    if not manifest_path.exists():
        abort(404, "File not found")

    with open(manifest_path) as f:
        manifest = json.load(f)

    if index < 0 or index >= manifest["chunk_count"]:
        abort(400, "Invalid chunk number")

    data = request.get_json()

    for field in ["nonce", "ciphertext", "hmac"]:
        if field not in data:
            abort(400, "Missing encrypted data")

    chunk_path = folder / f"{index}.json"

    with open(chunk_path, "w") as f:
        json.dump(data, f)

    return jsonify({"message": "Encrypted chunk stored"})


@app.route("/upload/<file_id>/finish", methods=["POST"])
def finish_upload(file_id):

    folder = STORAGE / file_id
    manifest_path = folder / "manifest.json"

    if not manifest_path.exists():
        abort(404)

    with open(manifest_path) as f:
        manifest = json.load(f)

    for i in range(manifest["chunk_count"]):
        if not (folder / f"{i}.json").exists():
            abort(400, "Missing chunk")

    manifest["complete"] = True

    with open(manifest_path, "w") as f:
        json.dump(manifest, f)

    return jsonify({"message": "Upload completed"})


@app.route("/files/<file_id>/manifest", methods=["GET"])
def get_manifest(file_id):

    path = STORAGE / file_id / "manifest.json"

    if not path.exists():
        abort(404)

    with open(path) as f:
        manifest = json.load(f)

    if not manifest["complete"]:
        abort(409)

    return jsonify(manifest)


@app.route("/files/<file_id>/<int:index>", methods=["GET"])
def get_chunk(file_id, index):

    folder = STORAGE / file_id
    manifest_path = folder / "manifest.json"

    if not manifest_path.exists():
        abort(404)

    with open(manifest_path) as f:
        manifest = json.load(f)

    if not manifest["complete"] or index < 0 or index >= manifest["chunk_count"]:
        abort(404)

    path = folder / f"{index}.json"

    if not path.exists():
        abort(404)

    with open(path) as f:
        return jsonify(json.load(f))


